import process from "node:process";
import { createClient } from "@supabase/supabase-js";

const supabaseUrl = process.env.SUPABASE_URL;
const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
const bucketName = process.env.SUPABASE_BUCKET ?? "wedding-photos";

if (!supabaseUrl || !serviceRoleKey) {
  console.error(
    "Missing SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY. Source .env.local first.",
  );
  process.exit(1);
}

const supabase = createClient(supabaseUrl, serviceRoleKey, {
  auth: {
    autoRefreshToken: false,
    persistSession: false,
  },
});

const { data: buckets, error: listError } = await supabase.storage.listBuckets();

if (listError) {
  console.error("Could not list buckets:", listError.message);
  process.exit(1);
}

const bucketExists = buckets.some((bucket) => bucket.name === bucketName);

if (!bucketExists) {
  const { error: createError } = await supabase.storage.createBucket(bucketName, {
    allowedMimeTypes: [
      "image/heic",
      "image/jpeg",
      "image/jpg",
      "image/png",
      "image/webp",
    ],
    fileSizeLimit: 10 * 1024 * 1024,
    public: false,
  });

  if (createError) {
    console.error("Could not create bucket:", createError.message);
    process.exit(1);
  }

  console.log(`Created bucket: ${bucketName}`);
} else {
  console.log(`Bucket already exists: ${bucketName}`);
}

console.log("");
console.log("Optional SQL for a metadata table:");
console.log(`
create table if not exists public.photos (
  id bigint generated by default as identity primary key,
  file_path text not null,
  created_at timestamptz not null default timezone('utc', now()),
  guest_name text
);
`);
